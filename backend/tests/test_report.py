"""Incident report page: GET /report/{id}, track-page button, detail fields."""
from backend.tests.test_telegram import _make_alert, tsetup  # noqa: F401


def _resolved_alert(client, key):
    alert_id = _make_alert(client, key).json()["alert_id"]
    r = client.post(f"/api/alerts/{alert_id}/safe")
    assert r.status_code == 200
    return alert_id


def test_report_page_serves(tsetup):
    client, key, db_path = tsetup
    alert_id = _resolved_alert(client, key)
    r = client.get(f"/report/{alert_id}")
    assert r.status_code == 200
    html = r.text
    assert 'id="print-btn"' in html
    assert "Generated by SilentSOS" in html
    assert 'id="r-summary"' in html
    assert 'id="r-map"' in html and 'id="r-trail-table"' in html
    assert 'id="r-contacts"' in html
    assert 'id="r-battery"' in html
    assert 'id="r-security"' in html
    assert 'rel="manifest"' in html
    assert "/i18n.js" in html
    assert "report.title" in html  # i18n wired


def test_report_page_unknown_id_is_404(tsetup):
    client, key, db_path = tsetup
    r = client.get("/report/no-such-alert")
    assert r.status_code == 404


def test_track_page_has_report_button(tsetup):
    client, key, db_path = tsetup
    alert_id = _make_alert(client, key).json()["alert_id"]
    r = client.get(f"/track/{alert_id}")
    assert r.status_code == 200
    assert 'id="report-btn"' in r.text
    assert "/report/" in r.text
    assert "track.report" in r.text  # i18n key


def test_alert_detail_includes_owner(tsetup):
    client, key, db_path = tsetup
    alert_id = _make_alert(client, key).json()["alert_id"]
    d = client.get(f"/api/alerts/{alert_id}").json()
    assert d["owner_name"] == "Test Owner"  # seeded device owner


def test_trail_points_record_battery(tsetup):
    from backend.tests.test_api import make_body, DEVICE_ID
    client, key, db_path = tsetup
    body = make_body(DEVICE_ID, key, typ="alert", battery=90)
    alert_id = client.post("/api/alert", json=body).json()["alert_id"]
    body2 = make_body(DEVICE_ID, key, typ="update", battery=85,
                      lat=27.0, lon=85.0)
    assert client.post("/api/alert", json=body2).status_code == 200
    trail = client.get(f"/api/alerts/{alert_id}").json()["trail"]
    assert [p["battery"] for p in trail] == [90, 85]
